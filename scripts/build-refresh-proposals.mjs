#!/usr/bin/env node
// Regenerates electron/refreshProposalData.ts from refresh-proposals/*.json.
//
// A refresh proposal is the reviewed list of published benefit changes that
// the app offers on the Quarterly Refresh screen. Keeping the source as JSON
// means the same file can be bundled with a release AND loaded by hand through
// "Load refresh file…". Run after adding or editing a proposal:
//   node scripts/build-refresh-proposals.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'refresh-proposals');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort();
const proposals = files.map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
const ids = new Set();
for (const p of proposals) {
  if (ids.has(p.proposal_id)) throw new Error(`Duplicate proposal_id ${p.proposal_id}`);
  ids.add(p.proposal_id);
}
const out = `// AUTO-GENERATED by scripts/build-refresh-proposals.mjs from refresh-proposals/*.json.
// Do not edit by hand: edit the JSON and re-run the script.
// tests/refreshProposal.test.ts validates every bundled proposal and checks
// that each change lines up with a benefit in a fully migrated database.

import type { RefreshProposal } from './types';

export const BUNDLED_REFRESH_PROPOSALS: RefreshProposal[] = ${JSON.stringify(proposals, null, 2)};
`;
fs.writeFileSync(path.join(root, 'electron', 'refreshProposalData.ts'), out);
console.log(`Wrote ${proposals.length} proposal(s): ${[...ids].join(', ')}`);
